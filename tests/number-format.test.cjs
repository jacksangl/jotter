const { test } = require('node:test');
const assert = require('node:assert/strict');
const { formatDecimal } = require('../src/number-format.js');

test('decimal results trim zero padding after hundredths and suppress tiny residue', () => {
  for (const [input, expected] of [
    ['13.5000000000', '13.50'], ['2.01000000000', '2.01'],
    ['135.00000001', '135'], ['134.99999999', '135'],
    ['-135.00000001', '-135'], ['13.50000001', '13.50'],
    ['4.00000000000', '4'], ['0.00000000000', '0'],
    ['13.5012300000', '13.50123'], ['135.000001', '135.000001'],
    ['0.739085133215', '0.739085133215'],
    ['0.00000001', '0.00000001'], ['-0.00000001', '-0.00000001'],
    ['1.50000000000e-20', '1.50e-20'], ['1.23456789012e+30', '1.23456789012e+30'],
    ['1000000000000.123', '1000000000000.123'],
    ['13.5000000000 - 135.00000001*I', '13.50 - 135*I'],
    ['-1000.0*I', '-1000*I'], ['I', 'I'], ['42', '42'],
  ]) assert.equal(formatDecimal(input), expected, input);
});
